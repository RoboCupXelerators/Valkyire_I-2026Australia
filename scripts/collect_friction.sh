#!/usr/bin/env bash
set -euo pipefail

# 采集真机摩擦/运动响应数据，输出 CSV 供调模拟器参数对齐。
# 在 Software 根目录下运行。

# 默认参数，可按需修改
: "${FRICTION_AXES:=x,y,w}"
: "${FRICTION_LEVELS:=8,12,16,20,24}"
: "${FRICTION_HOLD_S:=0.45}"
: "${FRICTION_COAST_S:=0.35}"
: "${FRICTION_SETTLE_S:=0.6}"
: "${FRICTION_SAMPLE_HZ:=20}"
: "${FRICTION_WARMUP_S:=8}"
: "${FRICTION_MOVE_EPS_CM:=1.2}"
: "${FRICTION_YAW_EPS_DEG:=3.0}"
: "${FRICTION_OUTPUT:=Records/friction}"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
cd "${REPO_ROOT}"

echo "[friction] collect start"
echo "FRICTION_AXES=${FRICTION_AXES}"
echo "FRICTION_LEVELS=${FRICTION_LEVELS}"
echo "FRICTION_HOLD_S=${FRICTION_HOLD_S}"
echo "FRICTION_COAST_S=${FRICTION_COAST_S}"
echo "FRICTION_SETTLE_S=${FRICTION_SETTLE_S}"
echo "FRICTION_SAMPLE_HZ=${FRICTION_SAMPLE_HZ}"
echo "FRICTION_WARMUP_S=${FRICTION_WARMUP_S}"
echo "FRICTION_OUTPUT=${FRICTION_OUTPUT}"

env \
  FRICTION_AXES="${FRICTION_AXES}" \
  FRICTION_LEVELS="${FRICTION_LEVELS}" \
  FRICTION_HOLD_S="${FRICTION_HOLD_S}" \
  FRICTION_COAST_S="${FRICTION_COAST_S}" \
  FRICTION_SETTLE_S="${FRICTION_SETTLE_S}" \
  FRICTION_SAMPLE_HZ="${FRICTION_SAMPLE_HZ}" \
  FRICTION_WARMUP_S="${FRICTION_WARMUP_S}" \
  FRICTION_MOVE_EPS_CM="${FRICTION_MOVE_EPS_CM}" \
  FRICTION_YAW_EPS_DEG="${FRICTION_YAW_EPS_DEG}" \
  FRICTION_OUTPUT="${FRICTION_OUTPUT}" \
  python -m src.tests.friction_real_sampling

EXIT_CODE=$?
echo "[friction] collect finished with exit code ${EXIT_CODE}"
exit ${EXIT_CODE}
